import {test,expect,type Page} from '@playwright/test'
import {PDFDocument,StandardFonts,degrees} from 'pdf-lib'
import {readFile} from 'node:fs/promises'

const ready=async(page:Page)=>{
  await expect(page.getByRole('button',{name:'PDFを保存',exact:true})).toBeEnabled()
  await expect(page.getByRole('alert')).toHaveCount(0)
}
const choose=(page:Page,value:string)=>page.getByRole('button',{name:`文字を選択: ${value}`,exact:true})

test('creates text and images, manages pages, merges PDFs, and undoes document changes',async({page,context},info)=>{
  test.setTimeout(180_000)
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button',{name:'新規PDF',exact:true}).click();await ready(page)
  await expect(page.getByRole('button',{name:'1ページへ',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'文字追加',exact:true}).click()
  await page.getByLabel('追加するテキスト').fill('最初のページ')
  await page.getByRole('button',{name:'PDFに追加',exact:true}).click();await ready(page)
  await expect(choose(page,'最初のページ')).toBeVisible()
  await page.getByRole('button',{name:'ページ追加',exact:true}).click();await ready(page)
  await expect(page.locator('.count-badge')).toHaveText('2')
  await page.getByRole('button',{name:'文字追加',exact:true}).click()
  await page.getByLabel('追加するテキスト').fill('二番目のページ')
  await page.getByRole('button',{name:'PDFに追加',exact:true}).click();await ready(page)
  await expect(choose(page,'二番目のページ')).toBeVisible()
  await page.getByRole('button',{name:'元に戻す',exact:true}).click();await ready(page)
  await expect(choose(page,'二番目のページ')).toHaveCount(0)
  await page.getByRole('button',{name:'やり直す',exact:true}).click();await ready(page)
  await expect(choose(page,'二番目のページ')).toBeVisible()
  await page.getByRole('button',{name:'2ページを前へ',exact:true}).click();await ready(page)
  await expect(choose(page,'二番目のページ')).toBeVisible()
  await expect(page.locator('.canvas-toolbar')).toContainText('1 / 2')
  await page.getByRole('button',{name:'1ページを回転',exact:true}).click();await ready(page)
  await choose(page,'二番目のページ').click()
  await page.getByLabel('変更後のテキスト').fill('回転したページ')
  await page.getByRole('button',{name:'変更を適用',exact:true}).click();await ready(page)
  await page.getByRole('button',{name:'画像追加',exact:true}).click()
  const image=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=20;c.height=10;const x=c.getContext('2d')!;x.fillStyle='#1987ac';x.fillRect(0,0,20,10);return c.toDataURL('image/png').split(',')[1]})
  await page.getByLabel('追加する画像ファイル').setInputFiles({name:'image.png',mimeType:'image/png',buffer:Buffer.from(image,'base64')})
  await page.getByLabel('上から（pt）',{exact:true}).fill('200')
  await page.getByRole('button',{name:'PDFに追加',exact:true}).click();await ready(page)
  await expect(choose(page,'回転したページ')).toBeAttached()
  await page.getByRole('button',{name:'図形追加',exact:true}).click()
  await page.getByLabel('図形の種類').selectOption('highlight')
  await page.getByLabel('上から（pt）',{exact:true}).fill('320')
  await page.getByRole('button',{name:'PDFに追加',exact:true}).click();await ready(page)
  const other=await PDFDocument.create();other.addPage().drawText('MERGED PAGE')
  await page.getByLabel('結合するPDFファイル',{exact:true}).setInputFiles({name:'merge.pdf',mimeType:'application/pdf',buffer:Buffer.from(await other.save())});await ready(page)
  await expect(page.locator('.count-badge')).toHaveText('3')
  await expect(choose(page,'MERGED PAGE')).toBeVisible()
  await page.getByRole('button',{name:'3ページを削除',exact:true}).click();await ready(page)
  await expect(page.locator('.count-badge')).toHaveText('2')
  await page.getByRole('button',{name:'元に戻す',exact:true}).click();await ready(page)
  await expect(page.locator('.count-badge')).toHaveText('3')
  const event=page.waitForEvent('download');await page.getByRole('button',{name:'PDFを保存',exact:true}).click()
  const output=info.outputPath('tools.pdf');await(await event).saveAs(output)
  const parsed=await PDFDocument.load(await readFile(output))
  expect(parsed.getPageCount()).toBe(3);expect(parsed.getPage(0).getRotation().angle).toBe(90)
  const reopened=await context.newPage();await reopened.goto('/')
  await reopened.getByLabel('PDFファイルを選択',{exact:true}).setInputFiles(output)
  await expect(choose(reopened,'回転したページ')).toBeAttached()
  await choose(reopened,'回転したページ').click();await expect(reopened.getByLabel('変更後のテキスト')).toBeEnabled()
  await page.screenshot({path:info.outputPath('tools.png'),fullPage:true})
  expect(errors).toEqual([])
})

test('supports serif bold, multiline text, free placement, and rotated text inside a page',async({page,context},info)=>{
  test.setTimeout(120_000)
  const pdf=await PDFDocument.create(),paper=pdf.addPage([600,800]),font=await pdf.embedFont(StandardFonts.Helvetica)
  paper.drawText('ROTATED ORIGINAL',{x:200,y:350,size:18,font,rotate:degrees(35)})
  paper.drawText('Plain text',{x:50,y:700,size:18,font})
  await page.goto('/')
  await page.getByLabel('PDFファイルを選択',{exact:true}).setInputFiles({name:'expanded.pdf',mimeType:'application/pdf',buffer:Buffer.from(await pdf.save())})
  await choose(page,'ROTATED ORIGINAL').click()
  await expect(page.getByLabel('変更後のテキスト')).toBeEnabled()
  await page.getByLabel('変更後のテキスト').fill('ROTATED UPDATED')
  await page.getByRole('button',{name:'変更を適用',exact:true}).click();await ready(page)
  await choose(page,'Plain text').click()
  await page.getByLabel('変更後のテキスト').fill('明朝体の編集\n二行目の文字')
  await page.getByLabel('書体',{exact:true}).selectOption('serif')
  await page.getByLabel('太字',{exact:true}).check()
  await page.getByLabel('元の領域に自動で収める',{exact:true}).uncheck()
  await page.getByLabel('文字サイズ',{exact:true}).fill('20')
  await page.getByLabel('横へ移動（pt）',{exact:true}).fill('12')
  await page.getByRole('button',{name:'変更を適用',exact:true}).click();await ready(page)
  await expect(page.locator('.font-note strong')).toHaveText('Noto Serif JP Bold')
  const event=page.waitForEvent('download');await page.getByRole('button',{name:'PDFを保存',exact:true}).click()
  const output=info.outputPath('expanded-text.pdf');await(await event).saveAs(output)
  const reopened=await context.newPage();await reopened.goto('/')
  await reopened.getByLabel('PDFファイルを選択',{exact:true}).setInputFiles(output)
  await expect(choose(reopened,'明朝体の編集\n二行目の文字')).toBeAttached()
  await choose(reopened,'明朝体の編集\n二行目の文字').click()
  await expect(reopened.getByLabel('元の領域に自動で収める',{exact:true})).not.toBeChecked()
  await expect(reopened.getByLabel('横へ移動（pt）',{exact:true})).toHaveValue('12')
})

test('rewrites an image-only document by dragging a region and preserves the rest of the page',async({page},info)=>{
  await page.goto('/')
  const data=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=600;c.height=800;const x=c.getContext('2d')!;x.fillStyle='white';x.fillRect(0,0,600,800);x.fillStyle='#111';x.font='20px sans-serif';x.fillText('SCANNED TEXT',60,120);x.fillStyle='#2687aa';x.fillRect(400,600,100,100);return c.toDataURL('image/png').split(',')[1]})
  const pdf=await PDFDocument.create();pdf.addPage([600,800]).drawImage(await pdf.embedPng(Buffer.from(data,'base64')),{x:0,y:0,width:600,height:800})
  await page.getByLabel('PDFファイルを選択',{exact:true}).setInputFiles({name:'scan.pdf',mimeType:'application/pdf',buffer:Buffer.from(await pdf.save())})
  await expect(page.locator('.inline-note')).toContainText('範囲書き換え')
  await page.getByRole('button',{name:'範囲書き換え',exact:true}).click()
  const sheet=await page.locator('.pdf-paper').boundingBox()
  await page.mouse.move(sheet!.x+55,sheet!.y+90);await page.mouse.down();await page.mouse.move(sheet!.x+260,sheet!.y+135);await page.mouse.up()
  await expect(page.getByLabel('左から（pt）',{exact:true})).toHaveValue('55')
  await page.getByLabel('追加するテキスト').fill('画像の文字を変更')
  await page.getByRole('button',{name:'この範囲を書き換える',exact:true}).click();await ready(page)
  await expect(choose(page,'画像の文字を変更')).toBeAttached()
  const event=page.waitForEvent('download');await page.getByRole('button',{name:'PDFを保存',exact:true}).click()
  await(await event).saveAs(info.outputPath('scan-rewritten.pdf'))
})

test('opens an encrypted PDF as a visual editing copy without sending the password or PDF',async({page,context})=>{
  const requests:string[]=[];context.on('request',r=>{if(/^https?:/.test(r.url())&&(r.method()!=='GET'||new URL(r.url()).origin!=='http://127.0.0.1:4173'))requests.push(r.url())})
  await page.goto('/')
  await page.getByLabel('PDFファイルを選択',{exact:true}).setInputFiles('e2e/fixtures/password.pdf')
  await expect(page.getByRole('dialog',{name:'パスワード付きPDFを開く'})).toBeVisible()
  await page.getByLabel('PDFのパスワード',{exact:true}).fill('wrong')
  await page.getByRole('button',{name:'画像化して開く',exact:true}).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('パスワード')
  await page.getByLabel('PDFのパスワード',{exact:true}).fill('test-pass')
  await page.getByRole('button',{name:'画像化して開く',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.inline-note')).toContainText('範囲書き換え')
  await ready(page)
  expect(requests).toEqual([])
})

test('rewrites overlapping source text and can edit the replacement after saving and reopening',async({page,context},info)=>{
  test.setTimeout(120_000)
  const pdf=await PDFDocument.create(),paper=pdf.addPage([600,800])
  paper.drawText('OVERLAP',{x:60,y:650,size:16});paper.drawText('OVERLAP',{x:60,y:650,size:16})
  await page.goto('/')
  await page.getByLabel('PDFファイルを選択',{exact:true}).setInputFiles({name:'overlap.pdf',mimeType:'application/pdf',buffer:Buffer.from(await pdf.save())})
  await choose(page,'OVERLAP').last().click()
  await expect(page.getByLabel('変更後のテキスト')).toBeDisabled()
  await page.getByRole('button',{name:'この範囲を指定して書き換える',exact:true}).click()
  await expect(page.getByLabel('追加するテキスト')).toHaveValue('OVERLAP')
  await page.getByLabel('追加するテキスト').fill('新しい文字')
  await page.getByRole('button',{name:'この範囲を書き換える',exact:true}).click();await ready(page)
  await expect(choose(page,'OVERLAP')).toHaveCount(0)
  await choose(page,'新しい文字').click()
  await expect(page.getByLabel('変更後のテキスト')).toBeEnabled()
  await page.getByLabel('変更後のテキスト').fill('再編集できる')
  await page.getByRole('button',{name:'変更を適用',exact:true}).click();await ready(page)
  const event=page.waitForEvent('download');await page.getByRole('button',{name:'PDFを保存',exact:true}).click()
  const output=info.outputPath('overlap-rewritten.pdf');await(await event).saveAs(output)
  const reopened=await context.newPage();await reopened.goto('/')
  await reopened.getByLabel('PDFファイルを選択',{exact:true}).setInputFiles(output)
  await expect(choose(reopened,'OVERLAP')).toHaveCount(0)
  await choose(reopened,'再編集できる').click()
  await expect(reopened.getByLabel('変更後のテキスト')).toBeEnabled()
  await reopened.getByRole('button',{name:'1ページを回転',exact:true}).click();await ready(reopened)
  await choose(reopened,'再編集できる').click()
  await expect(reopened.getByLabel('変更後のテキスト')).toBeEnabled()
})
