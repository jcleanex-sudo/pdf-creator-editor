import { test, expect, type Page } from '@playwright/test'
import { PDFDocument, StandardFonts } from 'pdf-lib'

const text = (page: Page, value: string) => page.getByRole('button', { name: `文字を選択: ${value}`, exact: true })
const saveReady = (page: Page) => expect(page.getByRole('button', { name: 'PDFを保存', exact: true })).toBeEnabled()

test('sample recalculates 209,000, undoes both amounts together, rejects bad amounts and saves the result', async ({ page, context }, info) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'サンプルPDFを試す' }).click()
  await text(page, '150,000').click()
  await expect(page.locator('.calculation-panel summary')).toContainText('有効・税率10%')
  await page.getByLabel('変更後のテキスト').fill('160,000')
  await page.getByRole('button', { name: '変更を適用', exact: true }).click()
  await saveReady(page)
  await expect(page.locator('.message')).toContainText('209,000円')
  await text(page, '209,000').click()
  await expect(page.getByLabel('変更後のテキスト')).toHaveValue('209,000')
  await expect(page.getByLabel('変更後のテキスト')).toBeDisabled()
  await page.getByRole('button', { name: '元に戻す', exact: true }).click()
  await saveReady(page)
  await expect(page.getByLabel('変更後のテキスト')).toHaveValue('198,000')
  await expect(page.locator('.status-left')).toContainText('0箇所の変更')
  await page.getByRole('button', { name: 'やり直す', exact: true }).click()
  await saveReady(page)
  await expect(page.getByLabel('変更後のテキスト')).toHaveValue('209,000')
  await text(page, '160,000').click()
  await page.getByRole('button', { name: 'この変更を取り消す', exact: true }).click()
  await saveReady(page)
  await text(page, '198,000').click()
  await expect(page.getByLabel('変更後のテキスト')).toHaveValue('198,000')
  await text(page, '150,000').click()
  await page.getByLabel('変更後のテキスト').fill('160,000')
  await page.getByRole('button', { name: '変更を適用', exact: true }).click()
  await saveReady(page)
  await page.getByLabel('変更後のテキスト').fill('1.5')
  await page.getByRole('button', { name: '変更を適用', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('整数')
  await expect(page.locator('.status-left')).toContainText('2箇所の変更')
  await page.getByLabel('変更後のテキスト').fill('160,000')
  const event = page.waitForEvent('download')
  await page.getByRole('button', { name: 'PDFを保存', exact: true }).click()
  const output = info.outputPath('auto-total.pdf')
  await (await event).saveAs(output)
  const reopened = await context.newPage()
  await reopened.goto('/')
  await reopened.locator('input[type=file]').setInputFiles(output)
  await expect(text(reopened, '160,000')).toBeAttached()
  await expect(text(reopened, '209,000')).toBeAttached()
  // Restore explicit source bindings rather than inferring hidden text.
  await expect(reopened.locator('.calculation-panel summary')).toContainText('有効・税率10%')
})

test('configures an uploaded PDF explicitly, recalculates decimal tax, and undoes the rule and its edits', async ({ page }) => {
  await page.goto('/')
  const pdf = await PDFDocument.create(), paper = pdf.addPage([600, 800])
  const font = await pdf.embedFont(StandardFonts.Helvetica)
  for (const [index, amount] of ['100', '200', '300'].entries())
    paper.drawText(amount, { x: 400, y: 700 - index * 50, size: 20, font })
  await page.locator('input[type=file]').setInputFiles({ name: 'invoice.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await pdf.save()) })
  await text(page, '100').click()
  await page.locator('.calculation-panel summary').click()
  await page.getByLabel('合計を書き込む欄').selectOption({ label: '300' })
  const amounts = page.getByRole('group', { name: '合計に含める明細金額' })
  await amounts.getByLabel('100', { exact: true }).check()
  await amounts.getByLabel('200', { exact: true }).check()
  await page.getByLabel('消費税率（%）').fill('8.25')
  await page.getByRole('button', { name: '計算設定を適用', exact: true }).click()
  await saveReady(page)
  await expect(page.locator('.calculation-summary')).toContainText('324円')
  await page.locator('.calculation-panel summary').click()
  await text(page, '100').click()
  await page.getByLabel('変更後のテキスト').fill('150')
  await page.getByRole('button', { name: '変更を適用', exact: true }).click()
  await saveReady(page)
  await text(page, '378').click()
  await expect(page.getByLabel('変更後のテキスト')).toHaveValue('378')
  await page.getByRole('button', { name: '元に戻す', exact: true }).click()
  await saveReady(page)
  await expect(page.getByLabel('変更後のテキスト')).toHaveValue('324')
  await page.getByRole('button', { name: '元に戻す', exact: true }).click()
  await saveReady(page)
  await expect(page.getByLabel('変更後のテキスト')).toHaveValue('300')
  await expect(page.getByLabel('変更後のテキスト')).toBeEnabled()
  await expect(page.locator('.calculation-panel summary')).toContainText('設定する')
})
