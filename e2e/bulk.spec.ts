import {test,expect,type Page} from '@playwright/test'
import {PDFDocument,StandardFonts,PDFDict,PDFName,PDFRef} from 'pdf-lib'
import {readFile} from 'node:fs/promises'
import {readProject} from '../src/pdf/project'

const ready=async(page:Page)=>{await expect(page.getByRole('button',{name:'PDFを保存',exact:true})).toBeEnabled();await expect(page.getByRole('alert')).toHaveCount(0)}
const choose=(page:Page,text:string)=>page.getByRole('button',{name:`文字を選択: ${text}`,exact:true})

test('searches all pages and replaces selected literal matches with formatting, explicit exclusions and atomic undo',async({page,context},info)=>{
  test.setTimeout(120_000)
  const errors:string[]=[],network:string[]=[]
  page.on('pageerror',error=>errors.push(error.message));context.on('request',r=>{if(/^https?:/.test(r.url())&&(new URL(r.url()).origin!=='http://127.0.0.1:4173'||r.method()!=='GET'))network.push(r.url())})
  const pdf=await PDFDocument.create(),normal=await pdf.embedFont(StandardFonts.Helvetica),bold=await pdf.embedFont(StandardFonts.HelveticaBold)
  const first=pdf.addPage([600,800]);first.drawText('Invoice (1) 2026',{x:60,y:650,size:16,font:normal});first.drawText('Invoice (2) 2026',{x:60,y:550,size:12,font:normal})
  pdf.addPage([600,800]).drawText('Invoice (3) 2026',{x:70,y:640,size:18,font:bold})
  const overlap=pdf.addPage([600,800]);for(let n=0;n<2;n++)overlap.drawText('Invoice (4) 2026',{x:60,y:650,size:16,font:normal})
  await page.goto('/')
  await page.getByLabel('PDFファイルを選択',{exact:true}).setInputFiles({name:'bulk.pdf',mimeType:'application/pdf',buffer:Buffer.from(await pdf.save())});await ready(page)
  await choose(page,'Invoice (1) 2026').click()
  await page.getByLabel('字幅（%）',{exact:true}).fill('90')
  await page.getByLabel('横へ移動（pt）',{exact:true}).fill('1.2')
  await page.getByRole('button',{name:'変更を適用',exact:true}).click();await ready(page)
  await page.getByRole('button',{name:'全文検索・置換',exact:true}).click()
  await page.getByLabel('検索する文字',{exact:true}).fill('Invoice (3)')
  await page.getByRole('button',{name:'全ページを検索',exact:true}).click()
  await expect(page.locator('.search-results .search-result')).toHaveCount(1)
  await page.locator('.search-result>button').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByLabel('変更後のテキスト',{exact:true})).toHaveValue('Invoice (3) 2026')
  await expect(page.locator('.canvas-toolbar')).toContainText('2 / 3')
  await expect(choose(page,'Invoice (3) 2026')).toBeInViewport()
  await page.getByRole('button',{name:'全文検索・置換',exact:true}).click()
  await page.getByLabel('検索する文字',{exact:true}).fill('2026')
  await page.getByLabel('置換する文字',{exact:true}).fill('2027')
  await page.getByRole('button',{name:'全ページを検索',exact:true}).click()
  await expect(page.locator('.search-results .search-result')).toHaveCount(5)
  await page.getByRole('button',{name:'選択した5領域を置換',exact:true}).click()
  await expect(page.locator('.batch-report')).toContainText('3領域を置換しました。2領域は変更していません。')
  await expect(page.locator('.batch-report')).toContainText('重な')
  await page.getByRole('button',{name:'全文検索を閉じる',exact:true}).click();await ready(page)
  await expect(choose(page,'Invoice (3) 2027')).toBeVisible()
  await page.getByRole('button',{name:'元に戻す',exact:true}).click();await ready(page)
  await expect(choose(page,'Invoice (3) 2026')).toBeVisible()
  await page.getByRole('button',{name:'やり直す',exact:true}).click();await ready(page)
  const event=page.waitForEvent('download');await page.getByRole('button',{name:'PDFを保存',exact:true}).click()
  const output=info.outputPath('bulk-edited.pdf');await(await event).saveAs(output)
  const project=readProject(await PDFDocument.load(await readFile(output)))!
  expect(project.project.edits).toHaveLength(3)
  expect(project.project.edits.find(edit=>edit.text==='Invoice (1) 2027')).toMatchObject({widthPercent:90,offsetX:1.2})
  expect(project.project.edits.find(edit=>edit.text==='Invoice (3) 2027')).toMatchObject({bold:true})
  const reopened=await context.newPage();await reopened.goto('/')
  await reopened.getByLabel('PDFファイルを選択',{exact:true}).setInputFiles(output);await ready(reopened)
  await expect(choose(reopened,'Invoice (1) 2027')).toBeVisible()
  await reopened.getByRole('button',{name:'2ページへ',exact:true}).click()
  await expect(choose(reopened,'Invoice (3) 2027')).toBeVisible()
  await reopened.getByRole('button',{name:'3ページへ',exact:true}).click()
  await expect(choose(reopened,'Invoice (4) 2026')).toHaveCount(2)
  expect(errors).toEqual([]);expect(network).toEqual([])
})

